import { createRequire } from 'node:module';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { startServer } from '../src/server.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../../..');
const {chromium}=createRequire(join(root,'deepseek-harness/apps/web/package.json'))('playwright');
const dir=await mkdtemp(join(tmpdir(),'aipm-ocr-browser-'));
const app=await startServer({port:0,dataDir:dir,bridge:{async close(){}}});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1500,height:980}});const errors=[];page.on('pageerror',error=>errors.push(error.message));
const call=async()=>{const response=await fetch(app.url+'/api/state',{headers:{'X-AIPM-Token':app.token}});return response.json();};
try{
  assert.equal((await call()).capabilities.ocr,true);
  await page.goto(app.url);
  await page.getByRole('button',{name:'新建项目',exact:true}).click();await page.locator('#project-form input').fill('OCR 界面验收');await page.getByRole('button',{name:'创建项目',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#modal').open);
  await page.getByRole('button',{name:'上传或填写',exact:true}).click();
  await page.locator('#input-form [name=file]').setInputFiles({name:'扫描访谈.pdf',mimeType:'application/pdf',buffer:await readFile(new URL('./fixtures/ocr-sample.pdf',import.meta.url))});
  await page.locator('.form-error').filter({hasText:'本机 OCR'}).waitFor();
  assert.equal((await call()).projects[0].inputs.length,0);
  await page.locator('#input-form [name=ocr]').check();
  await page.locator('.parse-status').filter({hasText:'提取完成'}).waitFor({timeout:30000});
  assert.match(await page.locator('#input-form [name=content]').inputValue(),/宠物陪伴/);
  assert.equal((await call()).projects[0].inputs.length,0);
  await page.locator('#input-form [name=content]').fill((await page.locator('#input-form [name=content]').inputValue())+'\n人工核对了访谈文字。');
  await page.locator('#toast').evaluate(element=>element.style.display='none');
  await page.screenshot({path:join(root,'产品经理工作台/原型截图/ocr-preview-v04.png')});
  await page.getByRole('button',{name:'加入当前模块',exact:true}).click();await page.waitForFunction(()=>!document.querySelector('#modal').open);
  const input=(await call()).projects[0].inputs[0];assert.equal(input.fileSource.method,'apple-vision-ocr');assert.equal(input.fileSource.edited,true);
  await page.getByRole('button',{name:'扫描访谈.pdf',exact:true}).click();await page.getByRole('heading',{name:'文件来源',exact:true}).waitFor();assert.ok(await page.getByText(/本机 OCR · 提取后已手工修改/).count());
  await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,checks:['扫描 PDF 失败可切换 OCR 重试','本机中英文识别预览','确认前不入库','编辑标记与来源','移动宽度'],pageErrors:errors}));
}finally{await browser.close();await app.close();await rm(dir,{recursive:true,force:true});}
